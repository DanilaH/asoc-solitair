import { mkdir, readFile, writeFile } from 'node:fs/promises';
const bank=JSON.parse(await readFile('.authoring/playtest246/bank.json','utf8'));
if(bank.schema!=='campaign-playtest246-v1'||Object.keys(bank.levels).length!==24)throw Error('Incomplete playtest admission');
const out='src/content/playtest246-bank', keys=Object.keys(bank.levels), names=[], groups=[];
await mkdir(out,{recursive:true});
for(let start=0;start<keys.length;start+=4){
  const name='shard-'+(start/4+1), subset=keys.slice(start,start+4);
  const json=JSON.stringify(Object.fromEntries(subset.map(key=>[key,bank.levels[key]])));
  await writeFile(`${out}/${name}.ts`,'// Own certified playtest data, generated by tools/content/build-playtest246.ts.\nexport default '+JSON.stringify(json)+';\n');
  names.push(name);groups.push(subset);
}
await writeFile(out+'/index.ts',names.map((name,i)=>`import shard${i} from './${name}';`).join('\n')+
  '\nexport const playtestShards = ['+names.map((_,i)=>'shard'+i).join(',')+'];\nexport const playtestShardKeys = '+JSON.stringify(groups)+';\n');
await mkdir('docs/qa/issue246',{recursive:true});
await writeFile('docs/qa/issue246/admission-v1.json',await readFile('.authoring/playtest246/admission.json','utf8')+'\n');
console.log('Packed24 sets /72 layouts, both reserve policies and all adaptive certificates');
