const images: Readonly<Record<string, string>> = {
  Свеча: 'candle', Верёвка: 'rope', Парусник: 'sailboat', Барабан: 'drum', Треугольник: 'triangle', Ель: 'spruce',
};
export function beyondCards(level: ChapterLevel): Record<string, Card> {
  const cards: Record<string, Card> = {};
  for (const [topic, [text, explanation, members]] of level.topics.entries()) {
    const category = `ru${level.level}-${topic + 1}`;
    cards[category] = { id: category, category, text, explanation, leader: true };
    for (const [index, word] of members.entries()) {
      const id = `${category}_${index + 1}`;
      const art = images[word];
      cards[id] = { id, category, text: word, explanation, ...(art ? { image: `art/generated/${art}.webp` } : {}) };
    }
  }
  return cards;
}
