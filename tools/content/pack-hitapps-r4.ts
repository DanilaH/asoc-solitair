import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { findDeal } from '../../src/content/campaign';
import type { SourceRecord } from '../../src/content/hitapps-r4-bank';
import { adjustedMoveBudget, C8_DIFFICULTY } from '../../src/domain/difficulty';
import { authoringHash } from './hitapps-authoring';
import { certifySourceRoute } from './hitapps-source-pipeline';

const inputFolder = '.authoring/hitapps-r4';
const outputFolder = 'src/content/hitapps-r4-bank';
const files = readdirSync(inputFolder).filter(file => /^(campaign|sweep|specials|compact-bound|locale|strategies)-\d+-of-\d+\.json$/.test(file));
const rows = files.flatMap(file => (JSON.parse(readFileSync(`${inputFolder}/${file}`, 'utf8')) as { records: SourceRecord[] }).records);
const distinct = new Map<string, SourceRecord>();
for (const record of rows) {
  const suffix = '-' + record.sourceHash.slice(0, 8);
  if (!record.deal.id.endsWith(suffix)) record.deal.id += suffix;
  const previous = distinct.get(record.deal.id);
  if (previous && previous.boardHash !== record.boardHash) throw Error(`Source ID has two boards: ${record.deal.id}`);
  distinct.set(record.deal.id, record);
}
const byLevel = new Map<number, SourceRecord[]>();
for (const record of distinct.values()) {
  const original = findDeal(record.baseId);
  if (!original || original.hitapps) throw Error(`Unknown seed template: ${record.baseId}`);
  const cards = Object.fromEntries(Object.entries({ ...original.cards, ...record.changedCards })
    .filter(([id]) => Object.hasOwn(record.deal.initial.hitapps!.cards, id)));
  const deal = { ...record.deal, cards };
  const level = deal.campaignLevel!, budget = deal.initial.movesLeft!;
  const proof = certifySourceRoute(deal, deal.winningPath);
  if (!proof || proof.cost !== record.cost || proof.traceHash !== record.traceHash || proof.routeHash !== record.routeHash ||
      authoringHash([deal.initial, deal.cards, deal.hitapps]) !== record.boardHash) throw Error(`Stored certificate mismatch: ${deal.id}`);
  const variants = record.use === 'campaign' ? [C8_DIFFICULTY.hardPenalty, C8_DIFFICULTY.easyPenalty].flatMap(penalty => {
    const moves = adjustedMoveBudget(budget, penalty, true);
    if (moves === budget || moves < proof.cost) return [];
    const board = { ...deal.initial, movesLeft: moves };
    const proofAtBudget = certifySourceRoute({ ...deal, initial: board }, deal.winningPath);
    if (!proofAtBudget || proofAtBudget.cost !== record.cost || proofAtBudget.reserve !== moves - record.cost)
      throw Error(`${deal.id} has no source Rules4 win at the adjusted budget`);
    return [[String(penalty), { moves, hash: authoringHash([board, deal.cards, deal.hitapps]) }]] as const;
  }) : [];
  const list = byLevel.get(level) ?? [];
  list.push({ ...record, ...(variants.length && { budgets: Object.fromEntries(variants) }) });
  byLevel.set(level, list);
}
mkdirSync(outputFolder, { recursive: true });
for (const [level, candidates] of byLevel) {
  candidates.sort((left, right) => left.use.localeCompare(right.use) || left.seed - right.seed || left.deal.id.localeCompare(right.deal.id));
  writeFileSync(`${outputFolder}/${String(level).padStart(3, '0')}.json`, `${JSON.stringify(candidates)}\n`);
}
const levels = [...byLevel.keys()].sort((left, right) => left - right);
const imports = levels.map(level => `import level${level} from './${String(level).padStart(3, '0')}.json' with { type: 'json' };`);
writeFileSync(`${outputFolder}/index.ts`, `// Generated by tools/content/pack-hitapps-r4.ts.\n${imports.join('\n')}
import type { SourceRecord } from '../hitapps-r4-bank';\n\nexport const sourceRecords = [${levels.map(level => `...level${level}`).join(', ')}] as unknown as readonly SourceRecord[];\n`);
console.log(JSON.stringify({ levels: byLevel.size, records: distinct.size }));
