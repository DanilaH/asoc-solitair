import { pauseOptions } from './qa/navigation';
import { mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { chromium, type Page } from '@playwright/test';
import { preview } from 'vite';
import { campaignDeals } from '../src/content/campaign';
import { dispatch, freshSave, packet } from '../src/domain/engine';
import { boardFrame, layout } from '../src/game/layout';
import type { Save } from '../src/domain/types';
const read = (p: Page) => p.evaluate(() => JSON.parse(localStorage.getItem('asoc-solitaire.save.v1')!) as Save);
const wait = (p: Page, ms = 650) => p.waitForTimeout(ms);
await mkdir('docs/qa', { recursive: true });
const server = await preview({ preview: { host: '127.0.0.1', port: 4189, strictPort: true } }), browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 360, height: 640 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, recordVideo: { dir: '.recording/review-video', size: { width: 360, height: 640 } } });
  const page = await context.newPage(), errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4189'); await page.waitForSelector('#app[data-ready="true"]');
  const deal = campaignDeals[16]; let index = 10, save = freshSave(deal, 'qa-layout-review');
  save.platform = { receipts: [], continuedAttempts: [], continueCredits: 0, lastFullscreenAt: 0, winsSinceInterstitial: 0, completedCampaign: campaignDeals.slice(0, 16).map(d => d.id) };
  while (deal.winningPath[index].type !== 'transfer') index++;
  for (const cmd of deal.winningPath.slice(0, index)) save = dispatch(save, cmd, deal).next;
  save.attempt.telemetry = { started: true, finished: false, activeMs: 0 };
  await page.evaluate(s => localStorage.setItem('asoc-solitaire.save.v1', JSON.stringify(s)), save);
  await page.reload(); await page.waitForSelector('#app[data-ready="true"]'); await page.locator('#home-play').tap(); await wait(page, 1000);
  await page.screenshot({ path: 'docs/qa/review-top-deck.png', scale: 'css' });
  await page.locator('#menu').tap(); await pauseOptions(page); await page.locator('#appearance-settings').tap();
  await page.locator('button[data-deck-position=bottom]').tap(); await page.locator('button[data-deck-side=left]').tap(); await wait(page);
  await page.screenshot({ path: 'docs/qa/review-layout-controls.png', scale: 'css' });
  await page.locator('#appearance .primary').tap(); await wait(page, 950);
  const before = await read(page);
  if (JSON.stringify(before.attempt.board) !== JSON.stringify(save.attempt.board)) throw Error('Layout changed the board');
  await page.screenshot({ path: 'docs/qa/review-bottom-deck.png', scale: 'css' });
  const cmd = deal.winningPath[index];
  if (cmd.type !== 'transfer') throw Error('Missing recording transfer');
  const rect = (await page.locator('canvas').boundingBox())!, frame = boardFrame(rect.width, rect.height, before.settings.deckPosition, deal);
  const g = layout(before.attempt.board, deal, frame.height, before.settings.deckSide, before.settings.deckPosition);
  const id = cmd.from.kind === 'waste' ? before.attempt.board.waste.at(-1) : packet(before.attempt.board, cmd.from.index, deal).at(-1);
  const source = g.poses.find(p => p.id === id)!, target = g.targets.find(t => t.location.kind === cmd.to.kind && t.location.index === cmd.to.index)!;
  const point = (p: {x: number; y: number}) => ({ x: rect.x + frame.offsetX + p.x * frame.unit, y: rect.y + p.y * frame.unit });
  const a = point(source), b = point(target), cdp = await context.newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [a] });
  for (let i = 1; i <= 14; i++) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: a.x + (b.x - a.x) * i / 14, y: a.y + (b.y - a.y) * i / 14 }] }); await wait(page, 24);
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await wait(page, 900);
  if ((await read(page)).attempt.board.movesLeft !== before.attempt.board.movesLeft! - 1) throw Error('Drag did not commit');
  await page.locator('#undo').tap(); await wait(page, 900);
  if (JSON.stringify((await read(page)).attempt.board) !== JSON.stringify(before.attempt.board)) throw Error('Undo changed the board');
  await page.locator('#menu').tap(); await pauseOptions(page); await page.locator('#appearance-settings').tap(); await page.locator('button[data-deck-side=right]').tap();
  await page.locator('#appearance .primary').tap(); await wait(page, 900);
  if (errors.length) throw Error(errors.join('\n'));
  const video = page.video()!; await context.close(); const file = '.recording/review-layout.webm'; await video.saveAs(file);
  execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-i', file, '-vf', 'fps=12,scale=360:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=128:stats_mode=diff[p];[b][p]paletteuse=dither=none:diff_mode=rectangle', 'docs/qa/review-layout.gif']);
  const proof = await browser.newPage({ viewport: { width: 320, height: 568 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
  await proof.goto('http://127.0.0.1:4189'); await proof.waitForSelector('#app[data-ready="true"]');
  const ordered = freshSave(campaignDeals[29], 'qa-guidance-review'); ordered.settings.reducedMotion = true;
  ordered.platform = { receipts: [], continuedAttempts: [], continueCredits: 0, lastFullscreenAt: 0, winsSinceInterstitial: 0, completedCampaign: campaignDeals.slice(0, 29).map(d => d.id) };
  await proof.evaluate(s => localStorage.setItem('asoc-solitaire.save.v1', JSON.stringify(s)), ordered); await proof.reload(); await proof.waitForSelector('#app[data-ready="true"]'); await proof.locator('#home-play').tap(); await wait(proof, 300);
  const size = await proof.locator('#message').evaluate(el => ({ height: el.clientHeight, content: el.scrollHeight }));
  if (size.content > size.height) throw Error('Guidance is clipped');
  await proof.screenshot({ path: 'docs/qa/review-guidance.png', scale: 'css' }); await proof.close();
  console.info('Recorded production touch layout / drag / Undo and compact guidance proof.');
} finally { await browser.close(); await new Promise<void>(resolve => server.httpServer.close(() => resolve())); }
